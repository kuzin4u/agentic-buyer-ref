// Маски идентификаторов (Р46 п. 1): одна копия на всё ядро. Идентификатор от Платформы, витрины или вызывающего — данные,
// не инструкция (инвариант 5): уходит в журнал, курсор и путь обращения только по маске — безопасные знаки, ограниченная длина.

/** До 128 знаков, как у Платформы: `mandate_id`, `event_id`, `op_ref`, ссылка заказа `ORDER_REF` (Р37 п. 3, Р45 п. 2.1). */
export const SAFE_ID = /^[A-Za-z0-9][A-Za-z0-9_.:-]{0,127}$/;

/** До 64 знаков: id витрины, `sku`, `merchant_id` в схеме адаптера витрин (Р38 п. 5, Р42). Код продавца в журнале конвейера
 *  — по `SAFE_ID`: он приходит и от других реализаций порта витрин (ревью reviewer К1 № 1). */
export const SHOP_ID = /^[A-Za-z0-9][A-Za-z0-9_.:-]{0,63}$/;

/** `confirmation_id` запроса подтверждения (Р47 п. 3): `cnf_` + UUID v4 строчными, как у Платформы (`src/confirm/model.ts`,
 *  РП50 п. 1). Не по форме — событие пропускается (`INVALID_DATA`), обращения нет. */
export const CONFIRMATION_ID = /^cnf_[0-9a-f]{8}-[0-9a-f]{4}-4[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/;
