import { describe, it, expect } from "vitest";
import { TRIAL_ITEMS, trialScope } from "@kuzin4u/agentic-core/trials";

// Матрица испытаний ядра (К19, v0.10.0; передача #38) — Р41 п. 3, вариант Б: подмодуль /trials подключён, область
// агента закреплена перечнем. Ситуации, свой TrialStand и полнота checkCoverage — с AG-20 (STATUS «Ждём от ядра»).
// Новый, снятый или переданный другому репозиторию пункт области роняет тест: нужна ситуация или основание «вне испытаний».
// Сравнение — без учёта порядка: перестановка пунктов в реестре ядра область не меняет. Правка текста развилки при том же
// составе тест не ловит — ловит её покрытие AG-20.
const AGENT_SCOPE = [
  // развилки чата Р-N (ссылка РЗ-N): события и подписка (Р-21…Р-26); копия ПАО, имена отказов, версия ПАО, CLOSED, KEY_EXPIRED (Р-27…Р-31)
  "РЗ-21", "РЗ-22", "РЗ-23", "РЗ-24", "РЗ-25", "РЗ-26", "РЗ-27", "РЗ-28", "РЗ-29", "РЗ-30", "РЗ-31",
  // допуск и старт (Р-37…Р-43)
  "РЗ-37", "РЗ-38", "РЗ-39", "РЗ-40", "РЗ-41", "РЗ-42", "РЗ-43",
  // объём AG-07, 3xx конфигурации, журналы агента и обращений, держимые мандаты (Р-62…Р-67); шум ленты (Р-76)
  "РЗ-62", "РЗ-63", "РЗ-64", "РЗ-65", "РЗ-66", "РЗ-67", "РЗ-76",
  // конфликты пула К-N (ссылка КП-N): КП-3, КП-6 — свои; КП-2, КП-17 — сквозные, против стенда Платформы
  "КП-2", "КП-3", "КП-6", "КП-17",
];

describe("матрица испытаний ядра — область агента (Р41 п. 3, передача #38)", () => {
  it("trialScope(\"agentic-buyer-ref\") — ровно 29 закреплённых пунктов", () => {
    const scope = trialScope("agentic-buyer-ref");
    expect(scope.map((i) => i.ref).sort()).toEqual([...AGENT_SCOPE].sort());
    expect(scope.every((i) => i.repo === "agentic-buyer-ref")).toBe(true);
  });

  // страж формата ссылки: вид пункта ядро выводит из префикса (РЗ- — развилка, КП- — конфликт пула)
  it("каждый пункт области есть в реестре ядра и вид совпадает со ссылкой", () => {
    for (const ref of AGENT_SCOPE) {
      const item = TRIAL_ITEMS.find((i) => i.ref === ref);
      expect(item, ref).toBeDefined();
      expect(item!.kind, ref).toBe(ref.startsWith("КП-") ? "conflict" : "fork");
    }
  });
});
